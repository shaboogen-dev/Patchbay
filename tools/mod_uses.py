#!/usr/bin/env python3
"""A mod's Bitwig dependencies: every Bitwig class, field and method its helper.jar can resolve.

  python tools/mod_uses.py list  <helper.jar> <bitwig.jar>     print uses.tsv
  python tools/mod_uses.py check <uses.tsv> <map-pack.zip> [<built-against build>]
                                                              list what the pack can't translate
                                                              (the build picks the remap when
                                                              the pack holds several)

A build is "<version>" for Windows or "<platform>-<version>" (macos, linux), e.g. macos-6.1.3, as
the tools name builds; a pack's own key ("windows-6.1.4") works too.

uses.tsv is generated by tools/build_mod.py into every release, in the names of the Bitwig build
the mod is built against. It is read from the constant pool, so it covers everything the JVM may
resolve: classes, field and method references (including lambda method handles), and the types in
the helper's own signatures. Only classes in bitwig.jar count; libs.jar and the JDK are not
obfuscated. build_mod.py also lists what the manifest's "fields" need translated: each owner and
each Bitwig class in a descriptor. A field's name is the mod's own, so it has no row. Rows, sorted:

  C  <class>
  F  <owner as referenced>  <name>  <desc>  <declaring class, or - when the JDK declares it>
  M  <owner as referenced>  <name>  <desc>  <declaring class, or - when the JDK declares it>

The declaring class is found in JVM resolution order (the class, its superclasses, then its
superinterfaces), which is what the pack must hold a row for; the loader translates the
referenced owner through its C row and the hierarchy.
"""
from __future__ import annotations
import functools, gzip, io, re, struct, sys, zipfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent / "jvm"))
import classfile as cf  # noqa: E402

DESC_CLASS = re.compile(r"L([^;]+);")
# java/lang/Object's methods a reference may name (a Bitwig interface declaring one doesn't take it from Object)
OBJECT_METHODS = {("equals", "(Ljava/lang/Object;)Z"), ("hashCode", "()I"), ("toString", "()Ljava/lang/String;"),
                  ("getClass", "()Ljava/lang/Class;"), ("notify", "()V"), ("notifyAll", "()V"), ("wait", "()V"),
                  ("wait", "(J)V"), ("wait", "(JI)V"), ("clone", "()Ljava/lang/Object;"), ("finalize", "()V")}


def pool_refs(data: bytes):
    """(classes, member refs, descriptors) named anywhere in one class file's constant pool,
    plus its super class, interfaces and own member descriptors."""
    n = struct.unpack_from(">H", data, 8)[0]
    pool, tags = [None] * n, [0] * n
    p, i = 10, 1
    while i < n:
        t = data[p]; tags[i] = t
        if t == 1:
            ln = struct.unpack_from(">H", data, p + 1)[0]
            pool[i] = data[p + 3:p + 3 + ln].decode("utf-8", errors="surrogateescape"); p += 3 + ln
        elif t in (7, 8, 16, 19, 20):
            pool[i] = struct.unpack_from(">H", data, p + 1)[0]; p += 3
        elif t in (9, 10, 11, 12, 17, 18):
            pool[i] = struct.unpack_from(">HH", data, p + 1); p += 5
        elif t in (3, 4):
            p += 5
        elif t in (5, 6):
            p += 9; i += 1
        elif t == 15:
            pool[i] = struct.unpack_from(">BH", data, p + 1); p += 4
        else:
            raise ValueError(f"constant tag {t}")
        i += 1
    classes, members, descs = set(), set(), set()
    for k in range(1, n):
        t = tags[k]
        if t == 7:
            classes.add(pool[pool[k]])
        elif t in (9, 10, 11):
            owner, nt = pool[k]
            name, desc = pool[pool[nt][0]], pool[pool[nt][1]]
            members.add(("F" if t == 9 else "M", pool[pool[owner]], name, desc))
            descs.add(desc)
        elif t == 16:
            descs.add(pool[pool[k]])
    c = cf.parse(data)
    classes |= {x for x in [c.super, *c.interfaces] if x}
    descs |= {d for _, d in c.fields} | {d for _, d in c.methods}
    return c.name, classes, members, descs


def plain(name: str) -> str | None:
    """Element class of a class or array name; None for primitive arrays."""
    name = name.lstrip("[")
    if name.startswith("L") and name.endswith(";"):
        return name[1:-1]
    return None if len(name) == 1 else name


class Bitwig:
    def __init__(self, jar: Path):
        self.z = zipfile.ZipFile(jar)
        self.names = {n[:-6] for n in self.z.namelist() if n.endswith(".class")}
        self.cache = {}

    def get(self, name):
        if name not in self.cache:
            self.cache[name] = cf.parse(self.z.read(name + ".class")) if name in self.names else None
        return self.cache[name]

    def declaring(self, kind, owner, name, desc):
        """Bitwig class declaring the member, '-' when resolution leaves bitwig.jar, None if not found.

        The superclass chain is walked first, then the superinterfaces, as the JVM resolves. When the chain
        leaves bitwig.jar (every chain ends in a JDK or libs.jar class) the superinterfaces are still searched:
        a Bitwig interface declaring the member is what the pack must translate. Only when no Bitwig class or
        interface declares it is it the JDK's ('-'). java/lang/Object's own methods are the JDK's even then."""
        table = "fields" if kind == "F" else "methods"
        c, chain, left_jar = owner, [], False
        while c:
            ci = self.get(c)
            if ci is None:
                if c == "java/lang/Object" and kind == "M" and (name, desc) in OBJECT_METHODS:
                    return "-"
                left_jar = True   # a JDK / libs.jar superclass may declare it: the interfaces come first to check
                break
            if (name, desc) in getattr(ci, table):
                return c
            chain.append(ci); c = ci.super
        todo = [i for ci in chain for i in ci.interfaces]
        seen = set()
        while todo:
            i = todo.pop(0)
            if i in seen:
                continue
            seen.add(i)
            ii = self.get(i)
            if ii is None:
                left_jar = True   # a JDK interface (Runnable, Comparable) may declare it
                continue
            if (name, desc) in getattr(ii, table):
                return i
            todo += ii.interfaces
        return "-" if left_jar else None


def uses(helper: bytes, bitwig_jar: Path) -> list[str]:
    bw = Bitwig(bitwig_jar)
    classes, members, descs, own = set(), set(), set(), set()
    with zipfile.ZipFile(io.BytesIO(helper)) as z:
        for n in sorted(z.namelist()):
            if n.endswith(".class") and not n.startswith("META-INF/"):
                me, c, m, d = pool_refs(z.read(n))
                own.add(me); classes |= c; members |= m; descs |= d
    for d in descs:
        classes |= set(DESC_CLASS.findall(d))
    rows = set()
    for c in classes:
        c = plain(c)
        if c and c in bw.names and c not in own:
            rows.add(f"C\t{c}")
    for kind, owner, name, desc in members:
        o = plain(owner)
        if o and o in bw.names:
            rows.add(f"C\t{o}")
            if not owner.startswith("["):
                dec = bw.declaring(kind, o, name, desc)
                rows.add(f"{kind}\t{o}\t{name}\t{desc}\t{dec or '?'}")
    return sorted(rows)


def with_fields(rows: list[str], manifest: dict) -> list[str]:
    """uses.tsv rows plus the classes a manifest's "fields" need translated."""
    out, targets = set(rows), manifest.get("targets", {})
    for f in manifest.get("fields", []):
        out.add(f"C\t{targets[f['owner']]['class'].replace('.', '/')}")
        out |= {f"C\t{t}" for t in DESC_CLASS.findall(f["descriptor"]) if not t.startswith("java/")}
    return sorted(out)


@functools.lru_cache(maxsize=4)  # a release checks every mod against each pack in turn
def pack_rows(pack: Path, source: str | None = None):
    """Rows of the pack's remap from `source` (the build the mod is built against); without a
    source the pack must hold only one remap. Callers only read the sets."""
    key = source if source is None or source.partition("-")[0] in ("windows", "macos", "linux") else f"windows-{source}"
    with zipfile.ZipFile(pack) as z:
        remaps = [x for x in z.namelist() if x.endswith(".tsv.gz")
                  and (key is None or Path(x).name.startswith(f"{key}__"))]
        if len(remaps) != 1:
            raise SystemExit(f"{pack.name}: expected one remap{f' from {source}' if source else ''}, found {len(remaps)}")
        n = remaps[0]
        rows = gzip.decompress(z.read(n)).decode().splitlines()
    classes = {r.split("\t")[1] for r in rows if r.startswith("C\t")}
    members = {tuple(r.split("\t")[:4]) for r in rows if r[:2] in ("F\t", "M\t")}
    return classes, members


def missing(uses_rows: list[str], pack: Path, source: str | None = None) -> list[str]:
    """Rows of uses.tsv the pack's remap from `source` can't translate, as readable lines."""
    classes, members = pack_rows(pack, source)
    out = []
    for r in uses_rows:
        f = r.split("\t")
        if f[0] == "C":
            if f[1] not in classes:
                out.append(f"class {f[1]}")
        elif f[4] == "?":
            out.append(f"{'field' if f[0] == 'F' else 'method'} {f[1]}.{f[2]}{f[3]} (not found in the built-against jar)")
        elif f[4] != "-" and (f[0], f[4], f[2], f[3]) not in members:
            out.append(f"{'field' if f[0] == 'F' else 'method'} {f[4]}.{f[2]}{f[3]}")
    return out


def main() -> int:
    if len(sys.argv) not in (4, 5) or sys.argv[1] not in ("list", "check") or (sys.argv[1] == "list" and len(sys.argv) == 5):
        print(__doc__); return 2
    if sys.argv[1] == "list":
        print("\n".join(uses(Path(sys.argv[2]).read_bytes(), Path(sys.argv[3]))))
        return 0
    gaps = missing(Path(sys.argv[2]).read_text("utf8").splitlines(), Path(sys.argv[3]), (sys.argv[4:] or [None])[0])
    for g in gaps:
        print("MISSING", g)
    print("USES_OK" if not gaps else f"USES_MISSING {len(gaps)}")
    return 1 if gaps else 0


if __name__ == "__main__":
    sys.exit(main())
