#!/bin/sh
# Starts Bitwig with the BML agent loaded when its JVM starts. The Linux and macOS counterpart of
# launch-bitwig-agent.cmd; launch-bitwig.sh calls it with the prepared runtime in the environment.
#   launch-bitwig-agent.sh [path to Bitwig's launcher, default /opt/bitwig-studio/bitwig-studio;
#                           macOS: Bitwig Studio.app, default the one in /Applications]
#
# Linux: Bitwig's launcher (bitwig-studio) starts the JVM as bin/BitwigStudio, a link to its bundled
# lib/jre/bin/java, with com.bitwig.flt.app.BitwigStudioMain as the main class.
# macOS: Bitwig's executable (Contents/MacOS/BitwigStudio) starts itself again as
# "BitwigStudio --launch", and that child runs the JVM inside its own process.
# The JVM reads JAVA_TOOL_OPTIONS from the environment it inherits, so -agentpath there loads the
# agent at JVM startup, as on Windows.
set -u
HERE=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
ROOT=$(CDPATH= cd -- "$HERE/../.." && pwd)
. "$HERE/../platform.sh"
bml_unquarantine "$ROOT"
if [ "$BML_OS" = Darwin ]; then AGENT="$HERE/bin/bitwig-jvmti-tracer.dylib"; OS_NAME=macOS
else AGENT="$HERE/bin/bitwig-jvmti-tracer.so"; OS_NAME=Linux; fi
SESSION="$HERE/bin/session.conf"
TARGETS=${BITWIG_TRACE_TARGETS:-$HERE/targets.tsv}
ACTIVE="$HERE/active-session.txt"
CONSOLE_LOG=${BML_BITWIG_CONSOLE_LOG:-$ROOT/state/bitwig-console.log}
BITWIG_LOG="$HOME/Library/Logs/Bitwig/BitwigStudio.log"  # macOS: where Bitwig writes its JVM's output
case "${BML_TRACE_ENABLED:-0}" in 1|true|TRUE|True) TRACE_ENABLED=1 ;; *) TRACE_ENABLED=0 ;; esac

debug() { if [ "${BML_DEBUG_VERBOSE:-}" = "1" ]; then echo "[BML debug] $*"; fi; }

debug "Checking native JVMTI loader binary..."
if [ ! -f "$AGENT" ]; then
  echo "ERROR: The BML agent for $OS_NAME is missing: $AGENT"
  echo "It is part of the BML release (built by loader/build.py); extract the whole release again."
  exit 4
fi

debug "Native loader binary is ready. Verifying Bitwig is not already running..."
# Exact JVMTI capabilities and class-load hooks must be acquired when this JVM starts.
RUNNING=$(bml_bitwig_running)
if [ -n "$RUNNING" ]; then
  echo "ERROR: Bitwig is already running (PID $RUNNING)."
  echo "Close Bitwig normally, then run this launcher again so the agent is present at JVM startup."
  exit 5
fi

BITWIG_EXE=$(bml_bitwig_exe "${1:-}")
if [ ! -f "$BITWIG_EXE" ]; then
  echo "ERROR: Bitwig launcher not found at:"
  echo "  $BITWIG_EXE"
  echo "Pass the full path as the first argument, for example:"
  if [ "$BML_OS" = Darwin ]; then
    echo "  launch-bitwig-agent.sh \"/Applications/Bitwig Studio.app\""
  else
    echo "  launch-bitwig-agent.sh /opt/bitwig-studio/bitwig-studio"
  fi
  exit 6
fi
BITWIG_EXE=$(bml_real_path "$BITWIG_EXE")
BITWIG_ROOT=$(dirname -- "$BITWIG_EXE")

TS=${BML_SESSION_ID:-$(date +%Y%m%d-%H%M%S)}
REPORT=""; TRACE=""; CONTROL=""
if [ "$TRACE_ENABLED" = "1" ]; then
  REPORT=${BML_SESSION_TRACE_ROOT:-$HERE/reports/trace-$TS}
  TRACE="$REPORT/trace.tsv"
  CONTROL="$REPORT/control.txt"
  mkdir -p "$REPORT"
fi

debug "Writing JVMTI session configuration (trace=$TRACE_ENABLED) ..."
{
  echo "# Generated by launch-bitwig-agent.sh"
  echo "trace_enabled=$TRACE_ENABLED"
  if [ "$TRACE_ENABLED" = "1" ]; then
    echo "targets=$TARGETS"
    echo "out=$TRACE"
    echo "control=$CONTROL"
    echo "stack=16"
    echo "receiver=1"
    echo "values=1"
    echo "tags=1"
    echo "strings=1"
    echo "string_limit=160"
    echo "inventory_classes=xyK,Gg3,Unc,K2Z,Itn,boJ,boo"
    echo "inventory_methods="
  fi
  if [ -n "${BITWIG_CLASS_HOOK_MODE:-}" ]; then echo "class_hook=$BITWIG_CLASS_HOOK_MODE"; fi
  if [ -n "${BITWIG_REPLACEMENT_CLASS:-}" ]; then echo "replacement_class=$BITWIG_REPLACEMENT_CLASS"; fi
  if [ -n "${BITWIG_REPLACEMENT_OWNER:-}" ]; then echo "replacement_owner=$BITWIG_REPLACEMENT_OWNER"; fi
  if [ -n "${BITWIG_REPLACEMENT_MAP:-}" ]; then echo "replacement_map=$BITWIG_REPLACEMENT_MAP"; fi
  if [ -n "${BITWIG_HELPER_JAR:-}" ]; then echo "helper_jar=$BITWIG_HELPER_JAR"; fi
} >"$SESSION"

{
  echo "session_id=$TS"
  echo "mode=modded"
  echo "trace_enabled=$TRACE_ENABLED"
  if [ "$TRACE_ENABLED" = "1" ]; then
    echo "report=$REPORT"
    echo "trace=$TRACE"
    echo "control=$CONTROL"
    echo "targets=$TARGETS"
  fi
  if [ -n "${BITWIG_REPLACEMENT_MAP:-}" ]; then echo "replacement_map=$BITWIG_REPLACEMENT_MAP"; fi
  if [ -n "${BITWIG_HELPER_JAR:-}" ]; then echo "helper_jar=$BITWIG_HELPER_JAR"; fi
  echo "launched=$TS"
  if [ -n "${BML_ENABLED_MOD_IDS:-}" ]; then echo "mod_ids=$BML_ENABLED_MOD_IDS"; fi
} >"$ACTIVE"

if [ "$TRACE_ENABLED" = "1" ]; then
  if [ -n "${BITWIG_ACCEPTANCE_LOG_IN_REPORT:-}" ]; then export BITWIG_RE_ACCEPTANCE_LOG="$REPORT/action-binding-acceptance.log"; fi
  if [ -n "${BITWIG_MOD_LOG_IN_REPORT:-}" ]; then export BITWIG_RE_MOD_LOG="$REPORT/mod.log"; fi
fi

debug "Session metadata prepared; launching Bitwig with the loader agent attached at JVM startup..."
# Only Bitwig started below inherits this; the user's other Java programs are unaffected.
export JAVA_TOOL_OPTIONS="${JAVA_TOOL_OPTIONS:+$JAVA_TOOL_OPTIONS }-agentpath:\"$AGENT\""
if [ "$TRACE_ENABLED" = "1" ]; then
  echo "Launching Bitwig with BML loader agent and Debug Mode tracing..."
  echo "Targets: $TARGETS"
else
  echo "Launching Bitwig with BML loader agent (Debug Mode off; tracing disabled)..."
fi
mkdir -p "$(dirname -- "$CONSOLE_LOG")"
: >"$CONSOLE_LOG"
LOG_ID_BEFORE=$(ls -i "$BITWIG_LOG" 2>/dev/null | awk '{print $1}')  # macOS: Bitwig's log before this launch
# Detached from this script and from BML (own session), so closing either leaves Bitwig running.
# What Bitwig's launcher prints goes to CONSOLE_LOG.
if command -v setsid >/dev/null 2>&1; then
  (cd "$BITWIG_ROOT" && setsid -f "$BITWIG_EXE" </dev/null >>"$CONSOLE_LOG" 2>&1)
else
  # (macOS has no setsid.) BML_NATIVE: arm64 on Apple silicon, even from a Rosetta Terminal.
  (cd "$BITWIG_ROOT" && nohup $BML_NATIVE "$BITWIG_EXE" </dev/null >>"$CONSOLE_LOG" 2>&1 &)
fi
if [ "$?" -ne 0 ]; then
  echo "ERROR: Failed to start Bitwig launcher process."
  exit 9
fi

debug "Bitwig launcher started; waiting for Bitwig's JVM..."
PID=""
n=0
while [ "$n" -lt 30 ]; do
  PID=$(bml_bitwig_pid)
  if [ -n "$PID" ]; then break; fi
  sleep 1
  n=$((n + 1))
done
if [ -z "$PID" ]; then
  echo "ERROR: Bitwig's JVM did not appear within 30 seconds. Last lines of $CONSOLE_LOG:"
  tail -n 20 "$CONSOLE_LOG" 2>/dev/null
  exit 7
fi
debug "Bitwig JVM process detected: PID $PID."
echo "pid=$PID" >>"$ACTIVE"
echo "Bitwig JVM PID: $PID"

# Confirm the agent is loaded: the JVM maps it into its memory when it loads it, before
# Bitwig's own code runs, and ends at once if the agent refuses to start. (Bitwig's launcher
# does not pass the JVM's console output on, so the agent's own start-up lines aren't seen.)
# Linux: the JVM's /proc/<pid>/maps; macOS: the files lsof lists as open in it.
agent_mapped() {
  if [ "$BML_OS" = Darwin ]; then
    lsof -p "$PID" -Fn 2>/dev/null | grep -qiF -e "n$AGENT_REAL"
  else
    grep -qF -- "$AGENT_REAL" "/proc/$PID/maps" 2>/dev/null
  fi
}
if [ "$BML_OS" = Darwin ]; then
  AGENT_REAL="$(CDPATH= cd -- "$(dirname -- "$AGENT")" && pwd -P)/$(basename -- "$AGENT")"
else
  AGENT_REAL=$(readlink -f -- "$AGENT")
fi
LOADED=0
n=0
while [ "$n" -lt 30 ]; do
  if agent_mapped; then LOADED=1; break; fi
  if ! bml_alive "$PID"; then break; fi
  sleep 0.5
  n=$((n + 1))
done
if [ "$LOADED" != "1" ]; then
  if bml_alive "$PID"; then
    echo "ERROR: Bitwig (PID $PID) is running, but the BML agent is not loaded in it: $AGENT_REAL"
  else
    echo "ERROR: Bitwig's JVM (PID $PID) ended during start-up; the BML agent may have refused to start."
  fi
  if [ "$BML_OS" = Darwin ]; then
    echo "See $CONSOLE_LOG and Bitwig's own log, $BITWIG_LOG."
  else
    echo "See $CONSOLE_LOG and Bitwig's own log."
  fi
  exit 10
fi
echo "Agent loaded in Bitwig's JVM: $AGENT_REAL"
# macOS: Bitwig writes its JVM's output, and so the agent's start-up line, to its own log, which
# it starts afresh at each launch (the previous one is moved aside: a new file).
if [ "$BML_OS" = Darwin ]; then
  n=0
  while [ "$n" -lt 10 ]; do
    LOG_ID=$(ls -i "$BITWIG_LOG" 2>/dev/null | awk '{print $1}')
    if [ -n "$LOG_ID" ] && { [ "$LOG_ID" != "$LOG_ID_BEFORE" ] || [ "$BITWIG_LOG" -nt "$SESSION" ]; }; then
      LINE=$(grep -F '[bitwig-jvmti] loaded' "$BITWIG_LOG" 2>/dev/null | tail -n 1)
      if [ -n "$LINE" ]; then echo "Bitwig's log ($BITWIG_LOG): $LINE"; break; fi
    fi
    sleep 0.5
    n=$((n + 1))
  done
fi

if [ "$TRACE_ENABLED" != "1" ]; then
  debug "Loader agent initialization confirmed; session is ready without tracing."
  echo
  echo "Loader agent started successfully. Debug Mode is off; no trace report was created."
  echo "Bitwig is running with the prepared external mods."
  exit 0
fi

debug "Waiting up to 90 seconds for Debug Mode tracer initialization/control file..."
# Require a populated "loaded" status, not just a file created before its first write.
n=0
while [ "$n" -lt 360 ]; do
  if [ -f "$CONTROL" ] && head -n 1 "$CONTROL" 2>/dev/null | grep -q '^loaded'; then
    debug "Tracer initialization confirmed; BML debug session is ready."
    echo
    echo "Loader agent started successfully with Debug Mode tracing:"
    cat "$CONTROL"
    echo
    echo "Trace: $TRACE"
    echo "Bitwig is running with the prepared external mods."
    exit 0
  fi
  sleep 0.25
  n=$((n + 1))
done
echo "WARNING: Bitwig started, but the tracer did not confirm initialization within 90 seconds."
echo "Check $CONSOLE_LOG for a JVM/agent startup error. Normal Bitwig launches are unaffected because JAVA_TOOL_OPTIONS was only set for this child process."
echo "Session metadata: $ACTIVE"
exit 8
